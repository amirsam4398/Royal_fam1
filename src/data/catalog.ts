const byPlace = new Map(places.map((place) => [place.slug, place]));
const byService = new Map(services.map((item) => [item.slug, item]));

export function getPlace(slug: string) {
  return byPlace.get(slug);
}

export function getService(slug: string) {
  return byService.get(slug);
}

export function placesOf(kind: PlaceKind) {
  return places.filter((place) => place.kind === kind);
}

export function servicesOf(tier: 1 | 2 | 3) {
  return services.filter((item) => item.tier === tier);
}

export const landingCount = places.length * services.length;

export function relatedServices(current: Service) {
  return services.filter((item) => item.tier === current.tier && item.slug !== current.slug).slice(0, 4);
}

export function siblingPlaces(current: Place) {
  return places.filter((place) => place.kind === current.kind && place.slug !== current.slug).slice(0, 4);
}
